    public static void DrawText(MonochromeRaster raster, int x, int y, string text, int scale = 2)
    {
        ArgumentOutOfRangeException.ThrowIfNegativeOrZero(scale);

        int cursor = x;
        foreach (char input in text.ToUpperInvariant())
        {
            if (!Glyphs.TryGetValue(input, out string[]? rows))
            {
                throw new ArgumentException($"The diagnostic pixel font does not contain '{input}'.", nameof(text));
            }

            for (int row = 0; row < rows.Length; row++)
            {
                for (int column = 0; column < rows[row].Length; column++)
                {
                    if (rows[row][column] == '1')
                    {
                        raster.FillRectangle(cursor + (column * scale), y + (row * scale), scale, scale);
                    }
                }
            }

            cursor += 6 * scale;
        }
    }
